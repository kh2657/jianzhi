import { test, expect } from '@playwright/test'
import { launchApp, navigateTo, rmTempDir, layoutAudit } from './helpers/launch'
import { mkdtempSync } from 'node:fs'
import { join } from 'node:path'
import { tmpdir } from 'node:os'

test.describe('紧凑工作区与独立 Idea 区域', () => {
  test('三组主入口保持稳定，Idea 区域不打断当前工作', async () => {
    const dir = mkdtempSync(join(tmpdir(), 'mathwb-compact-'))
    const app = await launchApp(dir, {}, { visible: true })
    const { page } = app
    try {
      await expect(page.locator('.workspace-primary .nav-item')).toHaveCount(3)
      await expect(page.locator('.workspace-primary .nav-item[aria-label="学习"]')).toBeVisible()
      await expect(page.locator('.workspace-primary .nav-item[aria-label="计划"]')).toBeVisible()
      await expect(page.locator('.workspace-primary .nav-item[aria-label="资料"]')).toBeVisible()
      await expect(page.locator('.workspace-tabs .nav-item[aria-label="笔记"]')).toBeVisible()
      const peers = page.getByRole('navigation', { name: '学习功能' })
      await expect(peers.getByRole('button')).toHaveCount(3)
      await expect(page.locator('.scope-bar-left')).toHaveText('工作空间学习')
      const workspace = page.getByRole('button', { name: '切换工作空间', exact: true })
      await workspace.click()
      await expect(workspace).toHaveAttribute('aria-expanded', 'true')
      await page.keyboard.press('Escape')
      await expect(workspace).toBeFocused()
      await workspace.click()
      await page.getByRole('menuitem', { name: '计划', exact: true }).click()
      await expect(page.getByRole('heading', { name: '待办', exact: true })).toBeVisible()
      await workspace.click()
      await page.getByRole('menuitem', { name: '学习', exact: true }).click()
      await navigateTo(page, 'Idea')
      await page.getByRole('button', { name: '返回学习工作区', exact: true }).click()
      await expect(page.getByLabel('搜索笔记')).toBeVisible()

      const before = page.locator('.view').first()
      await page.getByRole('button', { name: '记一下', exact: true }).click()
      const region = page.getByRole('region', { name: '想法随记' })
      await expect(region).toBeVisible()
      const area = region.locator('[aria-label="想法内容"]')
      await area.fill('关于一致连续性的一个想法')
      await page.getByRole('button', { name: '关闭想法' }).click()
      await expect(region).toBeHidden()
      await page.getByRole('button', { name: '记一下', exact: true }).click()
      await expect(region.locator('[aria-label="想法内容"]')).toHaveValue('关于一致连续性的一个想法')
      await expect(before).toBeVisible()
      await expect(page.locator('body')).not.toHaveCSS('overflow-x', 'scroll')

      await region.getByRole('button', { name: '记下来', exact: true }).click()
      await expect(region).toBeHidden()

      await navigateTo(page, 'Idea')
      await expect(page.locator('.ideas-view')).toBeVisible()
      const row = page.locator('.ideas-row', { hasText: '关于一致连续性的一个想法' })
      await expect(row).toBeVisible()
      await page.getByLabel('搜索想法').fill('一致连续性')
      await expect(row).toBeVisible()
      await row.getByRole('button', { name: '编辑' }).click()
      await row.getByLabel('编辑想法').fill('关于一致连续性的一个想法（已补充）')
      await row.getByLabel('编辑想法').press('Control+Enter')
      await expect(row).toContainText('已补充')
      await row.getByRole('button', { name: '归档' }).click()
      await expect(row).toHaveCount(0)
      await page.getByRole('button', { name: /已归档/ }).click()
      const archived = page.locator('.ideas-row', { hasText: '已补充' })
      await expect(archived).toBeVisible()
      await archived.getByRole('button', { name: '恢复' }).click()
      await expect(archived).toHaveCount(0)
      await page.getByRole('button', { name: /想法 ·/ }).click()
      await expect(page.locator('.ideas-row', { hasText: '已补充' })).toBeVisible()
      await page.locator('.ideas-row').getByRole('button', { name: '编辑', exact: true }).click()
      await page.getByLabel('编辑想法').fill('关于一致连续性的一个想法（离开前补充）')
      await page.locator('.workspace-primary [aria-label="计划"]').click()
      await expect(page.getByRole('heading', { name: '待办', exact: true })).toBeVisible()
      await navigateTo(page, 'Idea')
      await expect(page.locator('.ideas-row')).toContainText('离开前补充')
      await page.locator('.ideas-row').getByRole('button', { name: '转成笔记' }).click()
      await expect(page.locator('.note-title-input')).toHaveValue('关于一致连续性的一个想法（离开前补充）')
      await app.app.close()
      const relaunched = await launchApp(dir, {}, { visible: true })
      try {
        await navigateTo(relaunched.page, 'Idea')
        await relaunched.page.getByRole('button', { name: /已归档 ·/ }).click()
        await expect(relaunched.page.locator('.ideas-row', { hasText: '离开前补充' })).toBeVisible()
        await navigateTo(relaunched.page, '笔记')
        await expect(relaunched.page.locator('.note-item', { hasText: '离开前补充' })).toBeVisible()
        expect(relaunched.consoleErrors).toEqual([])
      } finally {
        await relaunched.app.close()
      }
    } finally {
      await app.app.close().catch(() => undefined)
      rmTempDir(dir)
    }
  })

  test('真实工作区：五种尺寸、不中断记录、独立查询与数学排版', async () => {
    const dir = mkdtempSync(join(tmpdir(), 'mathwb-compact-layout-'))
    const app = await launchApp(dir, {}, { visible: true })
    const { page } = app
    const networkErrors: string[] = []
    page.on('response', (r) => { if (r.status() >= 400) networkErrors.push(`${r.status()} ${r.url()}`) })
    page.on('requestfailed', (r) => { if (!r.failure()?.errorText.includes('ERR_ABORTED')) networkErrors.push(r.url()) })
    try {
      await page.evaluate(async () => {
        await window.api.noteCreate({ title: '完备性与一致收敛', bodyMd: '对紧空间 $K$，连续函数空间 $C(K)$ 在一致范数下是 Banach 空间。\n\n$$\\lVert f_n-f\\rVert_\\infty \\longrightarrow 0$$\n\n原文和公式保持各自的排版度量。' })
        await window.api.memoCreate({ text: '从反例理解逐点收敛与一致收敛的区别。' })
      })
      await navigateTo(page, '笔记')
      await page.getByLabel('搜索笔记').fill('完备性')
      await navigateTo(page, '文献')
      await page.getByLabel('检索文献（标题和关键词）').fill('独立文献查询')
      await navigateTo(page, '笔记')
      await expect(page.getByLabel('搜索笔记')).toHaveValue('完备性')
      await page.locator('.note-item').click()
      await expect(page.locator('.note-preview .katex').first()).toBeVisible()
      const markup = await page.locator('.note-preview .katex').first().innerHTML()
      for (const size of [{ width: 1366, height: 768 }, { width: 1512, height: 982 }, { width: 1920, height: 1080 }, { width: 2560, height: 1440 }, { width: 800, height: 900 }]) {
        await page.setViewportSize(size)
        await expect(page.locator('.activity-bar')).toHaveCSS('background-color', 'rgb(129, 0, 30)')
        const peerRects = await page.locator('.workspace-peers .nav-item').evaluateAll(els => els.map(el => { const r = el.getBoundingClientRect(); return { y: r.y, height: r.height, width: r.width } }))
        expect(new Set(peerRects.map(r => `${r.y}:${r.height}:${r.width}`)).size).toBe(1)
        await page.getByRole('button', { name: '记一下', exact: true }).click()
        const capture = page.getByRole('region', { name: '想法随记' })
        await expect(capture).toBeVisible()
        await page.getByLabel('想法内容').fill('尚未提交的推导线索')
        expect(await layoutAudit(page, `capture ${size.width}`)).toEqual([])
        const close = capture.getByRole('button', { name: '关闭想法' })
        expect(await close.evaluate((el) => { const r = el.getBoundingClientRect(); return el.contains(document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2)) })).toBe(true)
        if (size.width === 1512) await page.screenshot({ animations: 'disabled', path: 'docs/screenshots/implemented-2026-10-10/capture.png' })
        if (size.width === 800) await page.screenshot({ animations: 'disabled', path: 'docs/screenshots/implemented-2026-10-10/narrow.png' })
        await page.locator('.workspace-primary [aria-label="计划"]').click()
        await expect(capture).toBeVisible()
        await expect(page.getByLabel('想法内容')).toHaveValue('尚未提交的推导线索')
        await page.locator('.workspace-primary [aria-label="学习"]').click()
        await expect(page.locator('.note-title-input')).toHaveValue('完备性与一致收敛')
        await close.click()
        expect(await layoutAudit(page, `note ${size.width}`)).toEqual([])
      }
      await page.setViewportSize({ width: 1512, height: 982 })
      await page.locator('.reading-typesetting summary').click()
      await page.getByLabel('正文字体', { exact: true }).selectOption('tex')
      await page.getByLabel('阅读字号').selectOption('20')
      await expect(page.locator('.note-preview .katex').first()).toHaveCSS('font-size', '24.2px')
      expect(await page.locator('.note-preview .katex').first().innerHTML()).toBe(markup)
      expect(await page.evaluate(async () => (await document.fonts.load('20px KaTeX_Main')).length)).toBeGreaterThan(0)
      await page.getByLabel('正文字体', { exact: true }).selectOption('times')
      await page.getByLabel('阅读字号').selectOption('16')
      await page.locator('.reading-typesetting summary').click()
      await page.screenshot({ animations: 'disabled', path: 'docs/screenshots/implemented-2026-10-10/notes.png' })
      await navigateTo(page, 'Idea')
      await expect(page.locator('.ideas-row')).toBeVisible()
      await page.screenshot({ animations: 'disabled', path: 'docs/screenshots/implemented-2026-10-10/ideas.png' })
      await page.getByRole('button', { name: '切换主题', exact: true }).click()
      expect(await layoutAudit(page, 'burgundy dark')).toEqual([])
      await page.screenshot({ animations: 'disabled', path: 'docs/screenshots/implemented-2026-10-10/ideas-dark.png' })
      await page.getByRole('button', { name: '切换主题', exact: true }).click()
      await page.emulateMedia({ reducedMotion: 'reduce' })
      await page.getByRole('button', { name: '记一下', exact: true }).click()
      await expect(page.locator('.idea-capture-slot')).toHaveCSS('animation-name', 'none')
      await page.getByLabel('想法内容').dispatchEvent('keydown', { key: 'Enter', ctrlKey: true, isComposing: true })
      await expect(page.getByLabel('想法内容')).toHaveValue('尚未提交的推导线索')
      await page.evaluate(() => window.api.testQuickCapture())
      await expect(page.getByRole('dialog', { name: '速记', exact: true })).toBeVisible()
      await expect(page.getByRole('region', { name: '想法随记' })).toBeHidden()
      await page.keyboard.press('Escape')
      await expect(page.getByRole('dialog', { name: '速记', exact: true })).toBeHidden()
      await page.getByRole('button', { name: '记一下', exact: true }).click()
      await expect(page.getByLabel('想法内容')).toHaveValue('尚未提交的推导线索')
      expect(networkErrors).toEqual([])
      expect(app.consoleErrors).toEqual([])
    } finally { await app.app.close().catch(() => undefined); rmTempDir(dir) }
  })
})
